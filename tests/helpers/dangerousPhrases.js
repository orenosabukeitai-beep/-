/**
 * 「受給できると断定している文章」を見つけるための仕組みです。
 *
 * ■ なぜ単語の一致では駄目なのか
 *
 * 「必ず」という単語を禁止してしまうと、
 *   「最新情報は必ず公式サイトで確認してください」
 * という、むしろ書かなければいけない文章まではじかれてしまいます。
 *
 * そこでこのファイルでは、単語ではなく「言い回し」を見ます。
 *   危険 →「必ずもらえます」   （必ず ＋ 受け取れると断定）
 *   安全 →「必ず確認してください」（必ず ＋ 確認のお願い）
 *
 * ■ ルールを足したいとき
 *
 * 下の ルール一覧 に1件追加し、safety.test.js の
 * 「危険な文章の例」「安全な文章の例」の両方に文例を足してください。
 * 両方に足すことで、新しいルールが
 *   ・危険な文章をちゃんと捕まえるか
 *   ・安全な文章を誤って捕まえないか
 * の両方を確認できます。
 */

export const ルール一覧 = [
  {
    id: "受給の断定",
    説明: "「受給できます」のように、受け取れることを断定している",
    正規表現: /受給\s*(?:は|が)?\s*(?:でき(?:ます|る)|可能です|されます)/,
  },
  {
    id: "支給・給付の断定",
    説明: "「支給されます」のように、支給を断定している（「〜場合があります」は安全）",
    正規表現:
      /(?:支給|給付|採用|貸与)\s*され(?:ます|る)(?![^。]{0,8}(?:場合|可能性|こと|とき|かどうか))/,
  },
  {
    id: "あなたは対象、の断定",
    説明: "「あなたは対象です」のように、利用者を名指しで対象だと断定している",
    正規表現: /あなた(?:は|が|には|にも)[^。、]{0,15}(?:対象で|対象と?なり|受給|資格があ)/,
  },
  {
    id: "資格の断定",
    説明: "「資格があります」のように、受給資格を断定している",
    正規表現: /(?:受給|申請)?資格があ(?:ります|る)(?!か)/,
  },
  {
    id: "断定的な言葉＋受け取れる",
    説明: "「必ずもらえます」のように、強い断定と受け取りが結びついている",
    正規表現:
      /(?:必ず|確実に|間違いなく|絶対に)[^。]{0,25}(?:受給|支給|給付|採用|貸与|もらえ|借りられ)/,
  },
  {
    id: "もらえるの断定",
    説明: "「奨学金がもらえます」のように、受け取りを断定している",
    正規表現: /(?:奨学金|支援金|給付金|補助金)[^。]{0,12}(?:が|は|を)?もらえ(?:ます|る)/,
  },
  {
    id: "受けられるの断定",
    説明: "「この支援を受けられます」のように、利用を断定している",
    正規表現: /(?:奨学金|支援|制度)[^。]{0,10}(?:が|を)?受けられ(?:ます|る)(?!か)/,
  },
  {
    id: "対象だと言い切る",
    説明: "「対象です」のように、対象であることを言い切っている",
    正規表現: /(?:対象|該当)者?で(?:す|ある)(?!か)/,
  },
];

/**
 * 文章の中から危険な言い回しを探します。
 * 見つからなければ空の配列を返します。
 */
export function 危険な言い回しを探す(文章) {
  const 見つかったもの = [];
  const 行 = 文章.split("\n");

  行.forEach((一行, 番号) => {
    for (const ルール of ルール一覧) {
      const 一致 = 一行.match(ルール.正規表現);
      if (一致) {
        見つかったもの.push({
          行番号: 番号 + 1,
          ルールid: ルール.id,
          説明: ルール.説明,
          該当箇所: 一致[0],
          行の内容: 一行.trim(),
        });
      }
    }
  });

  return 見つかったもの;
}

/** テストが失敗したときに読みやすいメッセージを作ります */
export function 見つかったものを文章にする(ファイル名, 見つかったもの) {
  return 見つかったもの
    .map(
      (件) =>
        `\n  ${ファイル名}:${件.行番号}\n` +
        `    問題: ${件.説明}\n` +
        `    該当: 「${件.該当箇所}」\n` +
        `    行  : ${件.行の内容}`
    )
    .join("\n");
}
