// @vitest-environment node

/**
 * 安全性のテストです。
 *
 * このアプリは「受けられるかどうかを決めるサービス」ではありません。
 * うっかり断定的な表現を書いてしまうと、高校生が誤った判断をしかねません。
 *
 * そこで、人の注意力ではなく機械でそれを防ぎます。
 * 断定的な言い回しがコードやデータに混ざった瞬間、このテストが失敗します。
 */

import { describe, it, expect } from "vitest";
import { readFileSync, readdirSync, statSync, existsSync } from "node:fs";
import { join, relative } from "node:path";
import {
  危険な言い回しを探す,
  見つかったものを文章にする,
} from "./helpers/dangerousPhrases.js";

// npm test はプロジェクトのフォルダで実行されるので、そこを基準にします
const プロジェクトの場所 = process.cwd();

/* ============================================================
   その1：検出の仕組みそのものを確かめる

   「危険な文章を見つけられること」だけでなく
   「安全な文章を誤って止めないこと」も同じくらい大切です。
   ここが通らないと、正しい注意書きまで書けなくなってしまいます。
   ============================================================ */

const 危険な文章の例 = [
  "あなたはこの奨学金を受給できます。",
  "あなたは対象です。",
  "確実に受給できます。",
  "必ずもらえます。",
  "この制度の支援金がもらえます。",
  "受給資格があります。",
  "申請すれば支給されます。",
  "あなたには受給の権利があります。",
  "条件を満たしているので対象者です。",
  "この奨学金を受けられます。",
  "間違いなく採用されます。",
];

const 安全な文章の例 = [
  "最新情報は必ず公式サイトで確認してください。",
  "条件や金額、締切は必ず公式サイトか窓口で確認してください。",
  "条件に該当する可能性があります。最新の募集要項を公式サイトで確認してください。",
  "確認してみるとよい制度です。",
  "対象になると、授業料の支援と給付型奨学金の両方につながる場合があります。",
  "対象かどうかは家庭の状況などで決まります。",
  "返さなくてよいタイプの奨学金です。",
  "一部なら出してもらえそう",
  "だいたい出してもらえそう",
  "学費を家の人に出してもらえそうですか",
  "高校の進路担当の先生に直接聞くのがいちばん確実です。",
  "受けられるかどうかを決めるものではありません。",
  "これは「受けられる」という意味ではなく、「調べてみる価値がある」という意味です。",
  "給付される場合があります。",
  "支給される可能性があります。",
  "申し込みには家の人の協力が必要な制度が多いです。",
  "返す必要がないため、卒業後の負担がいちばん小さい種類の支援です。",
];

describe("危険な言い回しを見つける仕組み", () => {
  it.each(危険な文章の例)("危険な文章を見つけられる: %s", (文章) => {
    const 結果 = 危険な言い回しを探す(文章);
    expect(
      結果.length,
      `この文章は危険なので検出されるべきです → ${文章}`
    ).toBeGreaterThan(0);
  });

  it.each(安全な文章の例)("安全な文章を止めない: %s", (文章) => {
    const 結果 = 危険な言い回しを探す(文章);
    expect(
      結果,
      `この文章は安全なので検出してはいけません → ${文章}\n` +
        `誤って検出したルール: ${結果.map((r) => r.ルールid).join(", ")}`
    ).toEqual([]);
  });
});

/* ============================================================
   その2：実際のコードとデータを検査する
   ============================================================ */

/** 指定したフォルダの中から、対象の拡張子のファイルをすべて集める */
function ファイルを集める(フォルダ, 拡張子リスト) {
  if (!existsSync(フォルダ)) return [];
  const 集めたもの = [];

  for (const 名前 of readdirSync(フォルダ)) {
    if (名前 === "node_modules" || 名前.startsWith(".")) continue;
    const 場所 = join(フォルダ, 名前);

    if (statSync(場所).isDirectory()) {
      集めたもの.push(...ファイルを集める(場所, 拡張子リスト));
    } else if (拡張子リスト.some((拡張子) => 名前.endsWith(拡張子))) {
      集めたもの.push(場所);
    }
  }

  return 集めたもの;
}

// 検査する場所。第2段階で data/ に制度データを置くと、自動的に検査対象になります。
const 検査するファイル = [
  ...ファイルを集める(join(プロジェクトの場所, "src"), [".js", ".jsx"]),
  ...ファイルを集める(join(プロジェクトの場所, "data"), [".js", ".json"]),
  join(プロジェクトの場所, "index.html"),
].filter((場所) => existsSync(場所));

describe("アプリの中に断定的な表現がない", () => {
  it("検査するファイルが存在する", () => {
    expect(検査するファイル.length).toBeGreaterThan(0);
  });

  it.each(検査するファイル)("%s に断定的な表現がない", (場所) => {
    const 中身 = readFileSync(場所, "utf-8");
    const 見つかったもの = 危険な言い回しを探す(中身);
    const ファイル名 = relative(プロジェクトの場所, 場所);

    expect(
      見つかったもの,
      "受給を断定する表現が見つかりました。\n" +
        "「〜できます」ではなく「確認してみましょう」のような表現に直してください。" +
        見つかったものを文章にする(ファイル名, 見つかったもの)
    ).toEqual([]);
  });
});

/* ============================================================
   その3：必要な注意書きが消えていないことを確かめる
   ============================================================ */

describe("必要な注意書きが書かれている", () => {
  const 本体 = readFileSync(
    join(プロジェクトの場所, "src/ShingakuNavi.jsx"),
    "utf-8"
  );

  it("公式サイトでの確認を促している", () => {
    expect(本体).toMatch(/公式サイト/);
  });

  it("受給を決めるサービスではないと書いている", () => {
    expect(本体).toMatch(/決めるものではありません|決めることはできません/);
  });

  it("入力内容を保存しないと書いている", () => {
    expect(本体).toMatch(/保存されません|保存していません/);
  });

  it("個人を特定する情報を集めていない", () => {
    // 氏名・住所・電話番号・メールアドレスを入力させる項目が無いことを確認する
    expect(本体).not.toMatch(/type="email"|type="tel"|<input/);
  });
});
