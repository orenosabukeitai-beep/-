/**
 * data/programs/ フォルダにある制度データを、まとめて読み込みます。
 *
 * ■ 制度を増やしたいとき
 * data/programs/ に新しい JSON ファイルを置くだけです。
 * このファイルを含め、プログラムはいっさい書き換える必要がありません。
 *
 * ■ ファイル名の先頭の番号について
 * 「01-」「02-」といった番号は、画面に表示される順番です。
 * 番号の小さいものから順に並びます。
 * いちばん下に足したいときは、いまある最大の番号 ＋ 1 にしてください。
 *
 * ■ _TEMPLATE.json について
 * 新しい制度を作るときの雛形なので、制度としては読み込みません。
 */

// Vite の機能で、条件に合うファイルをまとめて読み込みます。
// eager: true は「あとで読むのではなく、今すぐ読む」という意味です。
const 読み込んだファイル = import.meta.glob("../../data/programs/*.json", {
  eager: true,
  import: "default",
});

/** 雛形ファイルかどうかを判定する */
function 雛形である(ファイルの場所) {
  return ファイルの場所.split("/").pop().startsWith("_");
}

export const 制度データ = Object.keys(読み込んだファイル)
  // 雛形は制度として扱わない
  .filter((場所) => !雛形である(場所))
  // ファイル名の順（＝先頭の番号の順）に並べる
  .sort()
  .map((場所) => 読み込んだファイル[場所]);

export default 制度データ;
