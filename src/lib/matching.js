/**
 * 回答から「確認する価値のある制度」を並べる処理です。
 *
 * ■ このアプリがしていないこと
 * 受けられるかどうかの判定はしていません。できません。
 * ここでやっているのは「確認する順番をつける」ことだけです。
 *
 * ■ 2つの仕組みに分けています
 *
 *   除外（excludeIf）… 公式の条件と回答を照らして、明らかに当てはまらないときだけ消す
 *   シグナル（signals）… 回答から見て「確認する価値がある」と言える手がかり
 *
 * 除外はとても慎重に使います。迷ったら残します。
 * 情報が足りないことを理由に制度を消すと、いちばん情報が届きにくい人に
 * いちばん届かなくなってしまうためです。
 */

/**
 * 「分からない」「答えない」にあたる回答。
 * これらを理由に制度を除外することは絶対にしません。
 */
export const 分からないことを表す回答 = ["skip", "unknown", "undecided"];

/** 回答が「分からない・答えない」かどうか */
function 分からない回答である(値) {
  return 値 === undefined || 値 === null || 分からないことを表す回答.includes(値);
}

/**
 * 明らかに対象外かどうかを判定します。
 *
 * 次の場合は、けっして「対象外」と判定しません。
 *   ・まだ答えていない
 *   ・「分からない」「答えない」を選んだ
 *   ・判断に必要な回答がそろっていない
 */
export function 明らかに当てはまらない(回答, excludeIf) {
  if (!excludeIf) return false;

  const 条件の項目 = Object.keys(excludeIf);
  if (条件の項目.length === 0) return false;

  // すべての条件がそろって初めて「対象外」と判断する
  return 条件の項目.every((項目) => {
    const 値 = 回答[項目];
    if (分からない回答である(値)) return false;
    return excludeIf[項目].includes(値);
  });
}

/** シグナルの条件に当てはまるか */
function シグナルに当てはまる(回答, when) {
  if (!when) return false;

  const 項目 = Object.keys(when);
  if (項目.length === 0) return false;

  return 項目.every((名前) => when[名前].includes(回答[名前]));
}

/**
 * データを、画面の並びに合わせて分けます。
 *
 * ■ program（実施主体がはっきりしている制度）は3つのグループへ
 *   特に確認したほうがよい … strong のシグナルが1つ以上
 *   確認する価値がある     … シグナルが1つ以上（strong は無い）
 *   知っておくとよい       … シグナルは無いが、対象外とも言い切れない
 *
 * ■ guide（学校・地域・民間などの確認先の案内）は別のまとまりへ
 *   guide は特定の1つの制度ではないため、制度と同じ並びに混ぜません。
 *   混ぜると、実在する1つの制度のように見えてしまいます。
 *
 * どのグループも「確認する順番」を表しているだけで、
 * 受け取れる見込みの大小を表すものではありません。
 */
export function 制度を分類する(回答, データ一覧) {
  const 特に確認したほうがよい = [];
  const 確認する価値がある = [];
  const 知っておくとよい = [];
  const 案内 = [];
  const 対象外 = [];

  for (const 制度 of データ一覧) {
    const 設定 = 制度.matching || {};

    if (明らかに当てはまらない(回答, 設定.excludeIf)) {
      対象外.push({ 制度, 回答にもとづく理由: [] });
      continue;
    }

    const 当てはまったシグナル = (設定.signals || []).filter((シグナル) =>
      シグナルに当てはまる(回答, シグナル.when)
    );

    const 項目 = {
      制度,
      回答にもとづく理由: 当てはまったシグナル.map((シグナル) => シグナル.reason),
    };

    if (制度.recordType === "guide") {
      案内.push(項目);
    } else if (当てはまったシグナル.some((シグナル) => シグナル.strength === "strong")) {
      特に確認したほうがよい.push(項目);
    } else if (当てはまったシグナル.length > 0) {
      確認する価値がある.push(項目);
    } else {
      知っておくとよい.push(項目);
    }
  }

  return { 特に確認したほうがよい, 確認する価値がある, 知っておくとよい, 案内, 対象外 };
}

/** 画面に出るすべてのもの（制度3グループ＋案内） */
export function 表示される制度(分類結果) {
  return [
    ...分類結果.特に確認したほうがよい,
    ...分類結果.確認する価値がある,
    ...分類結果.知っておくとよい,
    ...分類結果.案内,
  ];
}
